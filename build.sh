#!/bin/sh
# Build the Castle backend: SQLite + castle.c -> wasm.
#
#   ./build.sh          generate the schema, run the native self-test, build wasm
#   ./build.sh native   stop after the native self-test (no emsdk needed)
#
# Needs node, a host C compiler, and Emscripten. Emscripten is found on PATH, or
# via $EMSDK, or at the usual clone locations. An emsdk that was installed but
# never activated has no .emscripten config; rather than writing into your
# emsdk tree, this script generates one under build/.

set -e
cd "$(dirname "$0")"
mkdir -p build

SQLITE_FLAGS="-DSQLITE_THREADSAFE=0 \
 -DSQLITE_OMIT_LOAD_EXTENSION \
 -DSQLITE_ENABLE_DESERIALIZE \
 -DSQLITE_DQS=0 \
 -DSQLITE_DEFAULT_MEMSTATUS=0 \
 -DSQLITE_OMIT_PROGRESS_CALLBACK \
 -DSQLITE_OMIT_AUTOINIT \
 -DSQLITE_OMIT_DEPRECATED \
 -DSQLITE_OMIT_SHARED_CACHE \
 -DSQLITE_LIKE_DOESNT_MATCH_BLOBS \
 -DSQLITE_MAX_EXPR_DEPTH=0 \
 -DSQLITE_DEFAULT_FOREIGN_KEYS=1"

# ---------------------------------------------------------------- 1. schema --
if [ ! -f native/sqlite3.c ]; then
  echo "error: native/sqlite3.c is missing." >&2
  echo "Fetch the amalgamation from https://sqlite.org/download.html and unzip" >&2
  echo "sqlite3.c, sqlite3.h and sqlite3ext.h into native/." >&2
  exit 1
fi

echo "==> generating native/schema.sql from src/data/stub.js"
node native/gen-seed.mjs

echo "==> embedding it as native/schema_sql.h"
python3 - <<'PY'
# The seed SQL becomes one C string literal, split per source line so the
# generated header stays readable and diffable.
sql = open('native/schema.sql', encoding='utf-8').read()
def esc(line):
    return (line.replace('\\', '\\\\').replace('"', '\\"'))
with open('native/schema_sql.h', 'w', encoding='utf-8') as out:
    out.write('/* Generated by build.sh from schema.sql - do not edit. */\n')
    out.write('#ifndef CASTLE_SCHEMA_SQL_H\n#define CASTLE_SCHEMA_SQL_H\n\n')
    out.write('static const char SCHEMA_SQL[] =\n')
    for line in sql.splitlines():
        out.write('  "%s\\n"\n' % esc(line))
    out.write('  ;\n\n#endif\n')
print('native/schema_sql.h: %d bytes of SQL' % len(sql))
PY

# ------------------------------------------------------- 2. native selftest --
echo "==> building the native self-test"
cc -O1 -g -o build/castle-test \
  -I native $SQLITE_FLAGS \
  native/castle.c native/sqlite3.c -lm
echo "==> running it"
./build/castle-test

[ "$1" = "native" ] && { echo; echo "stopping after the native test, as asked"; exit 0; }

# ----------------------------------------------------------------- 3. wasm ---
if ! command -v emcc >/dev/null 2>&1; then
  for root in "$EMSDK" "$HOME/Documents/emsdk" "$HOME/emsdk" /opt/emsdk /usr/lib/emscripten; do
    [ -n "$root" ] && [ -x "$root/upstream/emscripten/emcc" ] || continue
    PATH="$root/upstream/emscripten:$PATH"
    export PATH
    # Activated emsdks have a config; freshly installed ones do not.
    if [ ! -f "$root/.emscripten" ] && [ -z "$EM_CONFIG" ]; then
      NODE_BIN=$(find "$root/node" -maxdepth 3 -type f -name node 2>/dev/null | head -1)
      [ -n "$NODE_BIN" ] || NODE_BIN=$(command -v node)
      cat > build/em.config <<EOF
LLVM_ROOT = '$root/upstream/bin'
BINARYEN_ROOT = '$root/upstream'
EMSCRIPTEN_ROOT = '$root/upstream/emscripten'
NODE_JS = '$NODE_BIN'
CACHE = '$root/upstream/emscripten/cache'
EOF
      EM_CONFIG="$PWD/build/em.config"
      export EM_CONFIG
      echo "==> using a generated emscripten config: build/em.config"
    fi
    break
  done
fi

if ! command -v emcc >/dev/null 2>&1; then
  echo "error: emcc not found. Install emsdk, or run ./build.sh native to stop" >&2
  echo "after the host-compiled self-test." >&2
  exit 1
fi

echo "==> building wasm ($(emcc --version 2>/dev/null | head -1))"
emcc -Oz -flto \
  -I native $SQLITE_FLAGS \
  native/castle.c native/sqlite3.c \
  -o src/data/castle.js \
  -s MODULARIZE=1 \
  -s EXPORT_ES6=1 \
  -s EXPORT_NAME=createCastle \
  -s ALLOW_MEMORY_GROWTH=1 \
  -s INITIAL_MEMORY=16MB \
  -s STACK_SIZE=1MB \
  -s FILESYSTEM=0 \
  -s ENVIRONMENT=web \
  -s EXPORTED_RUNTIME_METHODS=ccall,cwrap,UTF8ToString,stringToNewUTF8,HEAPU8 \
  -s EXPORTED_FUNCTIONS=_castle_init,_castle_query,_castle_sql_dump,_castle_db_size,_castle_db_read,_castle_free,_castle_last_error,_malloc,_free

ls -la src/data/castle.js src/data/castle.wasm

# A second, node-targeted build of the same C, so the JS<->wasm boundary - ccall
# marshalling, the serialise round trip through the heap - can be tested without
# a browser. The browser build cannot run under node (ENVIRONMENT=web).
echo "==> building a node-targeted copy for the test suite"
emcc -O1 \
  -I native $SQLITE_FLAGS \
  native/castle.c native/sqlite3.c \
  -o build/castle-node.mjs \
  -s MODULARIZE=1 \
  -s EXPORT_ES6=1 \
  -s EXPORT_NAME=createCastle \
  -s ALLOW_MEMORY_GROWTH=1 \
  -s FILESYSTEM=0 \
  -s ENVIRONMENT=node \
  -s EXPORTED_RUNTIME_METHODS=ccall,cwrap,UTF8ToString,HEAPU8 \
  -s EXPORTED_FUNCTIONS=_castle_init,_castle_query,_castle_sql_dump,_castle_db_size,_castle_db_read,_castle_free,_castle_last_error,_malloc,_free

echo "==> running the wasm boundary test"
node test/backend.mjs

echo
echo "built. ./serve.sh and open http://localhost:8000/"
