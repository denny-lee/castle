/*
 * The ledger for one box: every card with its completion, plus how many times
 * the box has been visited and for how long.
 *
 * Planned dates and drift are deliberately NOT computed here. They depend on an
 * anchor (the first completion) and on calendar arithmetic that JS does far
 * better than C, so this emits the raw facts and ledger.js does the sums.
 */
static void emit_ledger(Buf *b, int box_id) {
  sqlite3_stmt *st = NULL;

  buf_str(b, "{\"boxId\":");
  buf_int(b, box_id);

  /* subject name */
  buf_str(b, ",\"subject\":");
  sqlite3_prepare_v2(db, "SELECT label FROM boxes WHERE id = ?1", -1, &st, NULL);
  sqlite3_bind_int(st, 1, box_id);
  if (sqlite3_step(st) == SQLITE_ROW) buf_col_str(b, st, 0);
  else buf_str(b, "null");
  sqlite3_finalize(st);

  /* The anchor: the earliest completion, and which week it was. */
  buf_str(b, ",\"firstDoneAt\":");
  int first_week = 0;
  sqlite3_prepare_v2(db,
    "SELECT week_no, done_at FROM cards WHERE box_id = ?1 AND done_at IS NOT NULL"
    " ORDER BY done_at LIMIT 1", -1, &st, NULL);
  sqlite3_bind_int(st, 1, box_id);
  if (sqlite3_step(st) == SQLITE_ROW) {
    first_week = sqlite3_column_int(st, 0);
    buf_col_str(b, st, 1);
  } else {
    buf_str(b, "null");
  }
  sqlite3_finalize(st);
  buf_str(b, ",\"firstWeekNo\":");
  buf_int(b, first_week);

  /* Visits, and the time actually spent with a card out of this box. A session
   * with no ended_at was abandoned (the tab was closed); it is counted as a
   * visit but contributes no time, because its length is unknown. */
  sqlite3_prepare_v2(db,
    "SELECT COUNT(*),"
    " COALESCE(SUM(CASE WHEN ended_at IS NOT NULL"
    "   THEN (julianday(ended_at) - julianday(started_at)) * 86400.0 ELSE 0 END), 0),"
    " SUM(CASE WHEN ended_at IS NULL THEN 1 ELSE 0 END)"
    " FROM sessions WHERE box_id = ?1", -1, &st, NULL);
  sqlite3_bind_int(st, 1, box_id);
  double seconds = 0;
  int visits = 0, unfinished = 0;
  if (sqlite3_step(st) == SQLITE_ROW) {
    visits = sqlite3_column_int(st, 0);
    seconds = sqlite3_column_double(st, 1);
    unfinished = sqlite3_column_int(st, 2);
  }
  sqlite3_finalize(st);
  buf_str(b, ",\"visits\":");
  buf_int(b, visits);
  buf_str(b, ",\"unfinishedVisits\":");
  buf_int(b, unfinished);
  buf_str(b, ",\"seconds\":");
  buf_int(b, (long long)(seconds + 0.5));

  /* Every card in order, done or not. */
  buf_str(b, ",\"weeks\":[");
  sqlite3_prepare_v2(db,
    "SELECT id, seq, week_no, title, done_at,"
    " (SELECT COUNT(*) FROM tasks t WHERE t.card_id = c.id)"
    " FROM cards c WHERE box_id = ?1 ORDER BY seq", -1, &st, NULL);
  sqlite3_bind_int(st, 1, box_id);
  for (int i = 0; sqlite3_step(st) == SQLITE_ROW; i++) {
    if (i) buf_str(b, ",");
    buf_str(b, "{\"cardId\":");
    buf_int(b, sqlite3_column_int64(st, 0));
    buf_str(b, ",\"seq\":");
    buf_int(b, sqlite3_column_int(st, 1));
    buf_str(b, ",\"weekNo\":");
    buf_int(b, sqlite3_column_int(st, 2));
    buf_str(b, ",\"title\":");
    buf_col_str(b, st, 3);
    buf_str(b, ",\"doneAt\":");
    buf_col_str(b, st, 4);
    buf_str(b, ",\"taskCount\":");
    buf_int(b, sqlite3_column_int(st, 5));
    buf_str(b, "}");
  }
  sqlite3_finalize(st);
  buf_str(b, "]}");
}

/* Open a visit to a box. Returns the new session id. */
static char *session_start(int box_id, int card_id, const char *when) {
  sqlite3_stmt *st = NULL;
  if (sqlite3_prepare_v2(db,
        "INSERT INTO sessions (box_id, card_id, started_at, ended_at)"
        " VALUES (?1, ?2, ?3, NULL)", -1, &st, NULL) != SQLITE_OK) {
    set_error("session start");
    return json_error(last_error);
  }
  sqlite3_bind_int(st, 1, box_id);
  if (card_id > 0) sqlite3_bind_int(st, 2, card_id);
  else sqlite3_bind_null(st, 2);
  sqlite3_bind_text(st, 3, when && *when ? when : "1970-01-01T00:00:00.000Z", -1, SQLITE_TRANSIENT);
  int rc = sqlite3_step(st);
  sqlite3_finalize(st);
  if (rc != SQLITE_DONE) {
    set_error("session start");
    return json_error(last_error);
  }

  Buf b = {0};
  buf_str(&b, "{\"id\":");
  buf_int(&b, sqlite3_last_insert_rowid(db));
  buf_str(&b, "}");
  return buf_take(&b);
}

/* Close a visit. Closing an unknown or already-closed session is not an error:
 * the UI ends sessions from several places and must not have to track which
 * one got there first. */
static char *session_end(int session_id, const char *when) {
  sqlite3_stmt *st = NULL;
  sqlite3_prepare_v2(db,
    "UPDATE sessions SET ended_at = ?2 WHERE id = ?1 AND ended_at IS NULL",
    -1, &st, NULL);
  sqlite3_bind_int(st, 1, session_id);
  sqlite3_bind_text(st, 2, when && *when ? when : "1970-01-01T00:00:00.000Z", -1, SQLITE_TRANSIENT);
  sqlite3_step(st);
  int changed = sqlite3_changes(db);
  sqlite3_finalize(st);

  Buf b = {0};
  buf_str(&b, "{\"closed\":");
  buf_str(&b, changed ? "true" : "false");
  buf_str(&b, "}");
  return buf_take(&b);
}

/* Mark a card done, then report the card that rose to the top behind it. */
static char *mark_done(int card_id, const char *when) {
  sqlite3_stmt *st = NULL;
  sqlite3_prepare_v2(db, "SELECT box_id FROM cards WHERE id = ?1 AND done_at IS NULL",
                     -1, &st, NULL);
  sqlite3_bind_int(st, 1, card_id);
  if (sqlite3_step(st) != SQLITE_ROW) {
    sqlite3_finalize(st);
    return json_error("no such card, or it was already done");
  }
  int box_id = sqlite3_column_int(st, 0);
  sqlite3_finalize(st);

  sqlite3_prepare_v2(db, "UPDATE cards SET done_at = ?2 WHERE id = ?1 AND done_at IS NULL",
                     -1, &st, NULL);
  sqlite3_bind_int(st, 1, card_id);
  sqlite3_bind_text(st, 2, when && *when ? when : "1970-01-01T00:00:00.000Z", -1, SQLITE_TRANSIENT);
  int rc = sqlite3_step(st);
  sqlite3_finalize(st);
  if (rc != SQLITE_DONE) {
    set_error("mark done");
    return json_error(last_error);
  }

  Buf b = {0};
  buf_str(&b, "{\"nextCard\":");
  emit_top_card(&b, box_id);
  buf_str(&b, "}");
  return buf_take(&b);
}

