static void emit_boxes(Buf *b, sqlite3_int64 shelf_id) {
  /* The last three columns are the pace anchor (first completion) and the week
   * now waiting. The room needs them to flag an overdue box without asking for
   * a full ledger per box; the arithmetic itself stays in JS. */
  static const char *SQL =
    "SELECT b.id, b.label, b.level, b.slot,"
    " (SELECT COUNT(*) FROM cards c WHERE c.box_id = b.id),"
    " (SELECT COUNT(*) FROM cards c WHERE c.box_id = b.id AND c.done_at IS NOT NULL),"
    " (SELECT week_no FROM cards c WHERE c.box_id = b.id AND c.done_at IS NULL"
    "   ORDER BY c.seq LIMIT 1),"
    " (SELECT week_no FROM cards c WHERE c.box_id = b.id AND c.done_at IS NOT NULL"
    "   ORDER BY c.done_at LIMIT 1),"
    " (SELECT done_at FROM cards c WHERE c.box_id = b.id AND c.done_at IS NOT NULL"
    "   ORDER BY c.done_at LIMIT 1),"
    " b.priority"
    " FROM boxes b WHERE b.shelf_id = ?1 ORDER BY b.level, b.slot";

  sqlite3_stmt *st = NULL;
  sqlite3_prepare_v2(db, SQL, -1, &st, NULL);
  sqlite3_bind_int64(st, 1, shelf_id);
  buf_str(b, "[");
  for (int i = 0; sqlite3_step(st) == SQLITE_ROW; i++) {
    int total = sqlite3_column_int(st, 4);
    int done = sqlite3_column_int(st, 5);
    if (i) buf_str(b, ",");
    buf_str(b, "{\"id\":");
    buf_int(b, sqlite3_column_int64(st, 0));
    buf_str(b, ",\"label\":");
    buf_col_str(b, st, 1);
    buf_str(b, ",\"level\":");
    buf_int(b, sqlite3_column_int(st, 2));
    buf_str(b, ",\"slot\":");
    buf_int(b, sqlite3_column_int(st, 3));
    buf_str(b, ",\"cardCount\":");
    buf_int(b, total);
    buf_str(b, ",\"doneCount\":");
    buf_int(b, done);
    buf_str(b, ",\"remaining\":");
    buf_int(b, total - done);
    buf_str(b, ",\"activeWeekNo\":");
    if (sqlite3_column_type(st, 6) == SQLITE_NULL) buf_str(b, "null");
    else buf_int(b, sqlite3_column_int(st, 6));
    buf_str(b, ",\"firstWeekNo\":");
    if (sqlite3_column_type(st, 7) == SQLITE_NULL) buf_str(b, "null");
    else buf_int(b, sqlite3_column_int(st, 7));
    buf_str(b, ",\"firstDoneAt\":");
    buf_col_str(b, st, 8);
    buf_str(b, ",\"priority\":");
    buf_int(b, sqlite3_column_int(st, 9));
    buf_str(b, "}");
  }
  buf_str(b, "]");
  sqlite3_finalize(st);
}

static void emit_layout(Buf *b, int room_id) {
  sqlite3_stmt *st = NULL;
  sqlite3_prepare_v2(db,
    "SELECT id, number, wall, levels, slots FROM shelves WHERE room_id = ?1 ORDER BY number",
    -1, &st, NULL);
  sqlite3_bind_int(st, 1, room_id);

  /* Collect the shelf rows first: emit_boxes needs the statement machinery. */
  sqlite3_int64 ids[64];
  int numbers[64], levels[64], slots[64];
  char walls[64][8];
  int n = 0;
  while (n < 64 && sqlite3_step(st) == SQLITE_ROW) {
    ids[n] = sqlite3_column_int64(st, 0);
    numbers[n] = sqlite3_column_int(st, 1);
    snprintf(walls[n], sizeof walls[n], "%s", (const char *)sqlite3_column_text(st, 2));
    levels[n] = sqlite3_column_int(st, 3);
    slots[n] = sqlite3_column_int(st, 4);
    n++;
  }
  sqlite3_finalize(st);

  buf_str(b, "[");
  for (int i = 0; i < n; i++) {
    if (i) buf_str(b, ",");
    buf_str(b, "{\"id\":");
    buf_int(b, ids[i]);
    buf_str(b, ",\"number\":");
    buf_int(b, numbers[i]);
    buf_str(b, ",\"wall\":");
    buf_json_str(b, walls[i]);
    buf_str(b, ",\"levels\":");
    buf_int(b, levels[i]);
    buf_str(b, ",\"slots\":");
    buf_int(b, slots[i]);
    buf_str(b, ",\"boxes\":");
    emit_boxes(b, ids[i]);
    buf_str(b, "}");
  }
  buf_str(b, "]");
}

